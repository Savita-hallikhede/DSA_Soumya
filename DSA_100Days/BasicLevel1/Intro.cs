### 7. What is problem-solving in programming?

**Answer:**
Problem - solving in programming means **understanding a problem, creating a logical approach to solve it, and implementing that solution using code.**

For example, to find whether a number is even or odd:

1.Take the number.
2.Divide it by 2.
3. Check the remainder.
4. If the remainder is 0 → Even.
5. Otherwise → Odd.

