### 4. What is a Data Structure?

**Answer:**
A data structure is a way of **organizing and storing data** so that we can access and modify it efficiently.

**Example:**An array stores multiple elements in an organized manner.

---------------------------------------------------------------------------------------------------------------


### 5. What is an Algorithm?

**Answer:**
An algorithm is a * *step - by - step procedure used to solve a problem or perform a task**.

**Example:**The steps used to find the largest number in an array form an algorithm.

---------------------------------------------------------------------------------------------------------------


### 6. What is the difference between Data Structure and Algorithm?

**Answer:**

| Data Structure | Algorithm |
| ----------------------------- | ---------------------------------- |
| Organizes and stores data     | Solves a problem                   |
| Focuses on how data is stored | Focuses on how a task is performed |
| Example: Array, Stack, Queue  | Example: Searching, Sorting        |

**Simple way to remember:**
**Data Structure = How we store data**
**Algorithm = How we solve the problem**

